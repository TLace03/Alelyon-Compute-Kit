"""The 64-bit twins of a SPIR-V module's 16-bit float controls.

    python float_controls_64.py <in.spv> <out.spv>     pair them, print the count

A module that rounds with the device's own f32 -> f16 conversion declares its
float controls for 16-bit floats in GLSL (GL_EXT_spirv_intrinsics):
RoundingModeRTE (4462) and DenormPreserve (4459). A device whose float
controls are only 32-bit independent (VkPhysicalDeviceFloatControlsProperties:
VK_SHADER_FLOAT_CONTROLS_INDEPENDENCE_32_BIT_ONLY, as the RX 9070 XT reports)
requires an entry point to use the same modes for 16-bit and 64-bit floats,
and glslang keeps one declaration a mode. So this pass adds, beside each
16-bit `OpExecutionMode <entry> <mode> 16` of those two modes, the same
instruction with width 64.

Each added instruction is OpExecutionMode's four words with the width changed.
It adds no id, capability or extension (the 16-bit declarations brought them),
so the header's bound is unchanged. spirv-val checks the result in build.py.
Standard library only: it ships beside the modules, so a module MANIFEST.json
marks with `"post_pass": "float_controls_64.py"` is regenerated by the
compiler line followed by this pass (tests/languages/test_compute_kit_manifest.py).
"""
from __future__ import annotations

import struct
import sys

MAGIC = 0x07230203
OP_EXECUTION_MODE = 16
#: RoundingModeRTE and DenormPreserve (SPV_KHR_float_controls), and the
#: other float-control modes a sabotage build may declare in their place
#: (DenormFlushToZero 4460, SignedZeroInfNanPreserve 4461, RoundingModeRTZ 4463)
FLOAT_CONTROL_MODES = range(4459, 4464)


def pair(data: bytes) -> tuple[bytes, int]:
    """`data` with a 64-bit twin after every 16-bit float-control
    OpExecutionMode, and the number of twins added."""
    if len(data) % 4 or len(data) < 20:
        raise ValueError("not a SPIR-V module: its length is not whole words past the header")
    words = list(struct.unpack(f"<{len(data) // 4}I", data))
    if words[0] != MAGIC:
        raise ValueError("not a little-endian SPIR-V module (magic)")
    out, i, added = words[:5], 5, 0
    while i < len(words):
        count, opcode = words[i] >> 16, words[i] & 0xFFFF
        if count == 0:
            raise ValueError(f"an instruction of word count 0 at word {i}")
        inst = words[i:i + count]
        out.extend(inst)
        if opcode == OP_EXECUTION_MODE and count == 4 and inst[2] in FLOAT_CONTROL_MODES and inst[3] == 16:
            out.extend([inst[0], inst[1], inst[2], 64])
            added += 1
        i += count
    return struct.pack(f"<{len(out)}I", *out), added


def main(argv: list[str]) -> int:
    if len(argv) != 2:
        print(__doc__.strip().splitlines()[2].strip())
        return 2
    src, dst = argv
    with open(src, "rb") as f:
        data, added = pair(f.read())
    with open(dst, "wb") as f:
        f.write(data)
    print(f"{dst}: {added} 64-bit float-control twin(s) added")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
