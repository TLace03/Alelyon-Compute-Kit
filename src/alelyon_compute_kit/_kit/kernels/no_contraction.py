"""NoContraction on every float arithmetic result of a SPIR-V module.

    python no_contraction.py <in.spv> <out.spv>     decorate, print the count
    python no_contraction.py --check <module.spv>   exit 1 unless every result is decorated

NoContraction (decoration 42) on an arithmetic instruction forbids the
implementation to combine it with another into one operation -- a fused
multiply-add is the usual case -- so each result is rounded where the module
rounds it. GLSL's `precise` produces the same decoration, one expression at a
time. This pass puts it on EVERY float arithmetic result of a module, so no
float result is left to the driver's discretion.

Why (2026-09-30): the fp16 fused attention exists twice, once with integer
binary16 conversions and once with the device's own. Both compute the same
f32 values in the same order, yet on an RX 9070 XT they differed in the last
bit of a few outputs, because the driver contracted their f32 arithmetic
differently. The difference moved with changes that alter no value at all
(a declared float control; spirv-opt on or off). With this decoration on both
sets of modules, every output compared equal, bit for bit, and the kernels'
time did not measurably change (forward + backward 15.39 / 15.22 ms against
15.27 / 15.22 ms, and 12.21 / 12.18 ms against 12.30 / 12.18 ms, integer and
hardware sets, two rounds).

What it does not reach: extended instructions (exp2, log, an explicit fma),
whose precision stays the implementation's; the cooperative-matrix
multiply-add; conversions. It adds no ids, so the header's bound is unchanged,
and the new OpDecorate instructions go at the end of the annotation section,
in the order their targets appear. Standard library only; it ships beside the
modules, so a module MANIFEST.json marks with `"post_pass": "no_contraction.py"`
is regenerated by the compiler line followed by this pass.
"""
from __future__ import annotations

import struct
import sys

MAGIC = 0x07230203
OP_DECORATE = 71
NO_CONTRACTION = 42
#: OpFNegate, OpFAdd, OpFSub, OpFMul, OpFDiv, OpFRem, OpFMod, OpVectorTimesScalar,
#: OpMatrixTimesScalar, OpVectorTimesMatrix, OpMatrixTimesVector,
#: OpMatrixTimesMatrix, OpOuterProduct, OpDot: every core float arithmetic
#: instruction with a result, the second word of each being its result id
FLOAT_ARITHMETIC = frozenset({127, 129, 131, 133, 136, 138, 141, 142, 143, 144, 145, 146, 147, 148})
#: The sections that precede the first type: capabilities, extensions, extended
#: instruction imports, the memory model, entry points, execution modes, debug
#: instructions (strings, sources, names, processed markers) and annotations
PREAMBLE = frozenset({17, 10, 11, 14, 15, 16, 331, 7, 2, 3, 4, 5, 6, 330,
                      71, 72, 73, 74, 75, 332, 5632, 5633})


class NotSpirv(ValueError):
    """The bytes are not a well-formed little-endian SPIR-V module."""


def _instructions(data: bytes) -> tuple[list[int], list[list[int]]]:
    if len(data) < 20 or len(data) % 4:
        raise NotSpirv(f"{len(data)} bytes is not a SPIR-V module")
    words = list(struct.unpack(f"<{len(data) // 4}I", data))
    if words[0] != MAGIC:
        raise NotSpirv("not a little-endian SPIR-V module")
    header, body, insts, i = words[:5], words[5:], [], 0
    while i < len(body):
        count = body[i] >> 16
        if count == 0 or i + count > len(body):
            raise NotSpirv(f"a malformed instruction at word {i + 5}")
        insts.append(body[i:i + count])
        i += count
    return header, insts


def _decorated(insts: list[list[int]]) -> set[int]:
    return {inst[1] for inst in insts
            if inst[0] & 0xFFFF == OP_DECORATE and len(inst) >= 3 and inst[2] == NO_CONTRACTION}


def _results(insts: list[list[int]]) -> list[int]:
    return [inst[2] for inst in insts if inst[0] & 0xFFFF in FLOAT_ARITHMETIC and len(inst) >= 3]


def coverage(data: bytes) -> tuple[int, int]:
    """(float arithmetic results, how many of them carry NoContraction)."""
    _, insts = _instructions(data)
    results, done = _results(insts), _decorated(insts)
    return len(results), sum(1 for r in results if r in done)


def decorate(data: bytes) -> tuple[bytes, int]:
    """The module with NoContraction on every float arithmetic result, and how
    many results this call decorated (0 for a module that already had it)."""
    header, insts = _instructions(data)
    done = _decorated(insts)
    targets = [r for r in _results(insts) if r not in done]
    first = next((k for k, inst in enumerate(insts) if inst[0] & 0xFFFF not in PREAMBLE), len(insts))
    new = [[(3 << 16) | OP_DECORATE, target, NO_CONTRACTION] for target in targets]
    flat = header + [w for inst in insts[:first] + new + insts[first:] for w in inst]
    return struct.pack(f"<{len(flat)}I", *flat), len(targets)


def main(argv: list[str]) -> int:
    if len(argv) == 2 and argv[0] == "--check":
        with open(argv[1], "rb") as f:
            results, decorated = coverage(f.read())
        print(f"{argv[1]}: {decorated} of {results} float arithmetic results carry NoContraction")
        return 0 if decorated == results else 1
    if len(argv) != 2:
        print(__doc__.split("\n\n")[0])
        return 2
    with open(argv[0], "rb") as f:
        out, count = decorate(f.read())
    with open(argv[1], "wb") as f:
        f.write(out)
    print(f"{argv[0]}: {count} float arithmetic results decorated NoContraction")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
